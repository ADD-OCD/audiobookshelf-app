/**
 * Generates the native widget palette (android/app/src/main/res/values/widget_theme_colors.xml) from the
 * canonical built-in theme data, so the widget can't drift from the app. Only built-in themes with the
 * equipment finish get a native widget palette; the widget maps a fixed allow-list of theme ids to it
 * (widget/WidgetTheme.kt). Theme data never reaches native code at runtime.
 *
 * Usage: node scripts/generate-widget-theme.js          (writes the file)
 *        node scripts/generate-widget-theme.js --check  (exit 1 if the committed file is stale)
 * tests/widget-theme.test.mjs runs the same comparison.
 */
const fs = require('fs')
const path = require('path')
const engine = require('../theme/engine')
const presets = require('../theme/presets')

const OUTPUT = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'res', 'values', 'widget_theme_colors.xml')

// Native name suffix -> source token (fixed, repository-owned subset: only colors the widget resources use)
const TOKEN_COLORS = [
  ['base', 'surface.base'],
  ['content', 'surface.content'],
  ['raised', 'surface.raised'],
  ['recessed', 'surface.recessed'],
  ['text', 'text.primary'],
  ['text_muted', 'text.muted'],
  ['accent', 'accent.primary'],
  ['played', 'progress.played'],
  ['track', 'progress.track']
]

const hex = (rgb) => '#' + rgb.map((c) => c.toString(16).padStart(2, '0').toUpperCase()).join('')
const channelsToRgb = (value) => value.split(' ').map(Number)

function widgetThemes() {
  return engine.THEMES.filter((t) => t.tokens['presentation.finish'] === 'equipment')
}

function render() {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- GENERATED by scripts/generate-widget-theme.js from theme/builtins.js. Do not edit by hand. -->', '<resources>']
  for (const theme of widgetThemes()) {
    const prefix = `widget_${theme.id.replace(/-/g, '_')}`
    for (const [name, token] of TOKEN_COLORS) lines.push(`  <color name="${prefix}_${name}">${hex(theme.tokens[token])}</color>`)
    const derived = presets.equipmentDerivedDeclarations(theme.tokens)
    lines.push(`  <color name="${prefix}_edge_light">${hex(channelsToRgb(derived['--color-edge-light']))}</color>`)
    lines.push(`  <color name="${prefix}_edge_dark">${hex(channelsToRgb(derived['--color-edge-dark']))}</color>`)
  }
  lines.push('</resources>', '')
  return lines.join('\n')
}

module.exports = { render, OUTPUT, TOKEN_COLORS, widgetThemes }

if (require.main === module) {
  const expected = render()
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : ''
    if (actual !== expected) {
      console.error('widget_theme_colors.xml is stale: run node scripts/generate-widget-theme.js')
      process.exit(1)
    }
    console.log('widget_theme_colors.xml is up to date')
  } else {
    fs.writeFileSync(OUTPUT, expected)
    console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}`)
  }
}
